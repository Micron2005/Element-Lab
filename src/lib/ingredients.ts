export type Role =
  | "polymer"
  | "crosslinker"
  | "adhesive"
  | "plasticizer"
  | "solvent"
  | "filler";

export type CureMechanism =
  | "evaporation"
  | "ionic-bath"
  | "moisture"
  | "anionic"
  | "shear"
  | "cooling"
  | "covalent"
  | "none";

export type Hazard = 0 | 1 | 2 | 3;

export interface Ingredient {
  id: string;
  name: string;
  role: Role;
  formula: string;
  pubchemName?: string;
  /** Tensile strength of the cured solid, MPa (polymers / fillers). */
  tensileMPa?: number;
  /** Elongation at break, % (polymers). */
  elongationPct?: number;
  /** Stickiness 0-10. */
  tack: number;
  density: number;
  cure: CureMechanism[];
  /** Solvent the polymer needs to be dissolved in for spinning. */
  dissolvesIn?: string[];
  /** Polymers this crosslinker reacts with. */
  crosslinks?: string[];
  /** 0 safe, 1 mild, 2 harmful, 3 toxic. */
  toxicity: Hazard;
  skin: Hazard;
  edible: boolean;
  /** How water treats the cured material. */
  water: "dissolves" | "swells" | "resists";
  biodegradable: boolean;
  costPerKg: number;
  bonding: string;
  notes: string;
}

